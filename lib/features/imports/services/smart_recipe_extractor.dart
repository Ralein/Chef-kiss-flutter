/// Downloads recipe web pages for import.
class WebPageFetcher {
  static const int maxBytes = 5 * 1024 * 1024;
  final http.Client _client;
  WebPageFetcher([http.Client? client]) : _client = client ?? http.Client();

  Future<Result<String, AppFailure>> fetch(Uri url) async {
    if (!(url.isScheme('https') || url.isScheme('http')) || url.host.isEmpty) {
      return const Result.err(ValidationFailure(message: 'Enter a full web address starting with https://'));
    }
    try {
      final response = await _client.get(url, headers: const {
        'accept': 'text/html,application/xhtml+xml',
        'user-agent': "Mozilla/5.0 (compatible; ChefsKiss/1.0; +recipe-import)",
      }).timeout(const Duration(seconds: 20));
      if (response.statusCode >= 400) {
        return Result.err(RemoteFailure(
          statusCode: response.statusCode,
          message: 'That page could not be opened (HTTP ${response.statusCode}).',
        ));
      }
      if (response.bodyBytes.length > maxBytes) {
        return const Result.err(ValidationFailure(message: 'That page is too large to import.'));
      }
      return Result.ok(utf8.decode(response.bodyBytes, allowMalformed: true));
    } on TimeoutException {
      return const Result.err(RemoteFailure(message: 'The page took too long to load.'));
    } catch (_) {
      return Result.err(NetworkUnavailableFailure(
        message: kIsWeb
            ? 'Browsers block reading other websites directly.'
            : "Couldn't load that page.",
        recoveryAction: kIsWeb
            ? 'Copy the recipe text from the page and use “Paste text” instead.'
            : 'Check the address and your connection, or paste the recipe text instead.',
      ));
    }
  }
}

/// Routes each import source to the best available engine:
///
/// * pasted text — embedded JSON-LD (exact) → AI → offline heuristic parser
/// * web URL — page JSON-LD (exact) → AI over the page text
/// * photo — AI vision (required)
/// * prompt — AI generation (required)
class SmartRecipeExtractor implements DetailedRecipeExtractor {
  /// Page text beyond this is not sent to the model (≈ 30k tokens), and the
  /// review screen says so.
  static const int maxPageChars = 120000;

  final HeuristicRecipeExtractor _heuristic;
  final JsonLdRecipeParser _jsonLd;
  final WebPageFetcher _fetcher;

  /// Resolved per extraction so a key added in Settings takes effect without
  /// rebuilding the pipeline.
  final AiRecipeService? Function() _ai;

  SmartRecipeExtractor({
    required AiRecipeService? Function() ai,
    HeuristicRecipeExtractor? heuristic,
    JsonLdRecipeParser? jsonLd,
    WebPageFetcher? fetcher,
  })  : _ai = ai,
        _heuristic = heuristic ?? HeuristicRecipeExtractor(),
        _jsonLd = jsonLd ?? JsonLdRecipeParser(),
        _fetcher = fetcher ?? WebPageFetcher();

  static const _needsAi = CapabilityUnavailableFailure(
    capability: 'ai',
    reason: 'not_configured',
    message: 'This needs AI, which is not set up yet.',
    recoveryAction: 'Add an API key in Settings → AI & Scanning.',
  );

  @override
  Future<Result<Recipe, AppFailure>> extractRecipe({
    required ImportSource source,
    required String profileId,
    String? localeHint,
  }) async {
    final res = await extractDetailed(source: source, profileId: profileId);
    return res.map((e) => e.recipe);
  }

  @override
  Future<int> getRemainingDailyQuota(String profileId) async => 1 << 30;

  @override
  Future<Result<RecipeExtraction, AppFailure>> extractDetailed({
    required ImportSource source,
    required String profileId,
  }) async {
    final ai = _ai();
    switch (source.kind) {
      case ImportSourceKind.prompt:
        if (ai == null) return const Result.err(_needsAi);
        final prompt = source.rawText?.trim() ?? '';
        if (prompt.isEmpty) return const Result.err(ValidationFailure(message: 'Describe what you would like to cook.'));
        return (await ai.generate(prompt)).map((d) => RecipeExtraction(
              recipe: d.recipe.copyWith(profileId: profileId),
              confidence: 0.9,
              notes: [
                'Generated by AI — review quantities and timings before cooking.',
                ...d.warnings,
              ],
              engine: 'ai',
            ));

      case ImportSourceKind.image:
        if (ai == null) return const Result.err(_needsAi);
        final bytes = source.inlineData;
        if (bytes == null) return const Result.err(ValidationFailure(message: 'No photo was attached.'));
        final prepared = await ImagePrep.prepare(bytes, maxEdge: 2048);
        if (prepared.isFailure) return Result.err(prepared.error!);
        return (await ai.extractFromImage(prepared.orNull!)).map((d) => RecipeExtraction(
              recipe: d.recipe.copyWith(profileId: profileId),
              confidence: (0.85 - 0.1 * d.warnings.length).clamp(0.4, 0.85),
              notes: d.warnings,
              engine: 'ai',
            ));

      case ImportSourceKind.url:
        final url = Uri.tryParse((source.sourceUrl ?? source.rawText ?? '').trim());
        if (url == null) return const Result.err(ValidationFailure(message: 'That web address is not valid.'));
        final page = await _fetcher.fetch(url);
        if (page.isFailure) return Result.err(page.error!);
        final html = page.orNull!;

        final structured = _jsonLd.parse(html, profileId: profileId, sourceUrl: url.toString());
        if (structured != null && structured.ingredients.isNotEmpty) {
          return Result.ok(RecipeExtraction(recipe: structured, confidence: 0.95, engine: 'json-ld'));
        }
        if (ai == null) {
          return const Result.err(CapabilityUnavailableFailure(
            capability: 'ai',
            reason: 'not_configured',
            message: "This page doesn't publish structured recipe data.",
            recoveryAction: 'Paste the recipe text instead, or add an AI key in Settings to read any page.',
          ));
        }
        var text = JsonLdRecipeParser.htmlToText(html);
        final truncated = text.length > maxPageChars;
        if (truncated) text = text.substring(0, maxPageChars);
        return (await ai.extractFromText(text)).map((d) => RecipeExtraction(
              recipe: d.recipe.copyWith(profileId: profileId),
              confidence: (0.8 - 0.1 * d.warnings.length).clamp(0.4, 0.8),
              notes: [
                if (truncated) 'The page was very long; only its first part was read.',
                ...d.warnings,
              ],
              engine: 'ai',
            ));

      case ImportSourceKind.text:
      case ImportSourceKind.dictation:
      case ImportSourceKind.pdf:
        final text = source.rawText?.trim() ?? '';
        if (text.isEmpty) return const Result.err(ValidationFailure(message: 'Paste a recipe to import.'));
        final structured = _jsonLd.parse(text, profileId: profileId);
        if (structured != null && structured.ingredients.isNotEmpty) {
          return Result.ok(RecipeExtraction(recipe: structured, confidence: 0.95, engine: 'json-ld'));
        }
        if (ai != null) {
          final res = await ai.extractFromText(text);
          if (res.isSuccess) {
            final d = res.orNull!;
            return Result.ok(RecipeExtraction(
              recipe: d.recipe.copyWith(profileId: profileId),
              confidence: (0.88 - 0.1 * d.warnings.length).clamp(0.4, 0.88),
              notes: d.warnings,
              engine: 'ai',
            ));
          }
          // Fall back to the offline parser rather than failing the import.
        }
        final local = await _heuristic.extractRecipe(source: source, profileId: profileId);
        return local.map((recipe) => RecipeExtraction(
              recipe: recipe,
              confidence: _heuristicConfidence(recipe),
              notes: const ['Parsed offline — check that ingredients and steps were split correctly.'],
              engine: 'heuristic',
            ));
    }
  }

  static double _heuristicConfidence(Recipe r) {
    var score = 0.25;
    if (r.ingredients.length >= 2) score += 0.2;
    if (r.steps.isNotEmpty) score += 0.2;
    if (r.ingredients.isNotEmpty) {
      score += 0.2 * r.ingredients.where((i) => i.quantity != null).length / r.ingredients.length;
    }
    return score.clamp(0.0, 0.8);
  }
}
